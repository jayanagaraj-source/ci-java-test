CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254)             NOT NULL,
    password_hash VARCHAR(100)             NOT NULL,
    role          VARCHAR(16)              NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

-- Single-row table used to hand out the ADMIN role exactly once, atomically,
-- even when two registrations race.
CREATE TABLE app_state (
    id             INT     PRIMARY KEY,
    admin_assigned BOOLEAN NOT NULL,
    CONSTRAINT ck_app_state_single_row CHECK (id = 1)
);
INSERT INTO app_state (id, admin_assigned) VALUES (1, FALSE);

CREATE TABLE tasks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT                   NOT NULL,
    title         VARCHAR(200)             NOT NULL,
    description   VARCHAR(5000),
    status        VARCHAR(16)              NOT NULL,
    priority      VARCHAR(16)              NOT NULL,
    priority_rank INTEGER                  NOT NULL,
    due_date      DATE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    version       BIGINT                   NOT NULL,
    CONSTRAINT fk_tasks_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH'))
);
CREATE INDEX ix_tasks_owner_created ON tasks (owner_id, created_at);
CREATE INDEX ix_tasks_owner_status ON tasks (owner_id, status);

CREATE TABLE task_tags (
    task_id BIGINT      NOT NULL,
    tag     VARCHAR(40) NOT NULL,
    CONSTRAINT pk_task_tags PRIMARY KEY (task_id, tag),
    CONSTRAINT fk_task_tags_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE
);
CREATE INDEX ix_task_tags_tag ON task_tags (tag);
